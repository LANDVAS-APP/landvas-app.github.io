// Writes supabase/migrations/20261120000020_skywright_data.sql from the game's own star code (src/stars/galaxy.ts), so the
// database and the phone agree on every real star's kind and distance and on what each kind of star is.
//   npx tsx scripts/make-skywright-sql.ts
// The real stars (to magnitude 6) come from d3-celestial's data (BSD-3), itself from the HYG database (CC BY-SA 2.5):
// src/stars/realStars.json.
import fs from 'node:fs';
import path from 'node:path';
import { CLASSES, realStar, type RealCatalog } from '../src/stars/galaxy';

const cat = JSON.parse(fs.readFileSync(path.resolve('src/stars/realStars.json'), 'utf8')) as RealCatalog;
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const out: string[] = [];
out.push(`-- ✨ Skywright data (generated by scripts/make-skywright-sql.ts from src/stars/galaxy.ts — don't edit by hand)
-- * private.sw_classes: every kind of star (its shell's frequency m → 10·m² + 2 plots, its element ladder, its light)
-- * public.real_stars: the ~5,000 real stars you can see with your eyes, at their real places, with their kind and distance
--   (from d3-celestial's data, BSD-3, itself from the HYG database, CC BY-SA 2.5)

create table if not exists private.sw_classes (
  id text primary key, name text not null, emoji text not null, m int not null, weight int not null,
  color text not null, glow text not null, light text not null, fuse int not null, sort int not null);
insert into private.sw_classes (id, name, emoji, m, weight, color, glow, light, fuse, sort) values
${CLASSES.map((c, i) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.emoji)}, ${c.m}, ${c.weight}, ${q(c.color)}, ${q(c.glow)}, ${q(c.light)}, ${c.fuse}, ${i})`).join(',\n')}
on conflict (id) do update set name = excluded.name, emoji = excluded.emoji, m = excluded.m, weight = excluded.weight, color = excluded.color,
  glow = excluded.glow, light = excluded.light, fuse = excluded.fuse, sort = excluded.sort;

create table if not exists public.real_stars (
  hip int primary key, ra_md int not null, dec_md int not null, mag_c int not null, bv_m int not null,
  con text, name text not null, cls text not null, ly numeric(10,1) not null);
alter table public.real_stars enable row level security;
revoke all on public.real_stars from anon, authenticated;
`);
const rows = cat.stars.map((r) => {
  const s = realStar(r, cat);
  return `(${r[0]}, ${r[1]}, ${r[2]}, ${r[3]}, ${r[4]}, ${s.con ? q(s.con) : 'null'}, ${q(s.name)}, ${q(s.cls)}, ${s.ly})`;
});
for (let i = 0; i < rows.length; i += 500) {
  out.push(`insert into public.real_stars (hip, ra_md, dec_md, mag_c, bv_m, con, name, cls, ly) values\n  ${rows.slice(i, i + 500).join(',\n  ')}\non conflict (hip) do update set name = excluded.name, cls = excluded.cls, ly = excluded.ly, con = excluded.con;\n`);
}
fs.writeFileSync(path.resolve('supabase/migrations/20261120000020_skywright_data.sql'), out.join('\n'));
console.log(`wrote ${rows.length} real stars, ${CLASSES.length} kinds`);
