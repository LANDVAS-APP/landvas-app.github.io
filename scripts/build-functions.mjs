// Bundle each Edge Function (and the shared game/pipeline code it imports) into a
// single self-contained file that the Supabase CLI deploys as-is.
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
for (const name of ['minigame-finish', 'pipeline']) {
  const outfile = path.join(ROOT, 'supabase/functions', name, 'index.ts');
  fs.mkdirSync(path.dirname(outfile), { recursive: true });
  const r = await build({
    entryPoints: [path.join(ROOT, 'supabase/functions-src', `${name}.ts`)],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    mainFields: ['module', 'main'],
    conditions: ['import', 'module', 'default'],
    write: false,
    legalComments: 'none',
    banner: { js: '// @ts-nocheck\n// Generated by scripts/build-functions.mjs from supabase/functions-src — do not edit.' },
  });
  fs.writeFileSync(outfile, r.outputFiles[0].text);
  console.log(`${name}: ${(r.outputFiles[0].text.length / 1024).toFixed(0)} KB`);
}
