-- ---- held? (by city id, by state, by country) ------------------------------------------------------------------------
create or replace function private.crown_held(p_city text) returns boolean language sql stable as $$
  select exists (select 1 from public.world_plots p where p.rarity = 'crown' and p.owner_id is not null and p.city_id = p_city::int)
$$;
create or replace function private.crown_state_held(p_country text, p_state text) returns boolean language sql stable as $$
  select exists (select 1 from public.world_plots p join public.world_cities c on c.id = p.city_id
                  where p.rarity = 'crown_state' and p.owner_id is not null and c.country = p_country and c.state = p_state)
$$;
create or replace function private.crown_country_held(p_country text) returns boolean language sql stable as $$
  select exists (select 1 from public.world_plots p join public.world_cities c on c.id = p.city_id
                  where p.rarity = 'crown_country' and p.owner_id is not null and c.country = p_country)
$$;

-- ---- the roll: Country, then State, then City (each only while its kingdom has none) ----------------------------------
do $$
declare d text; n text;
begin
  d := pg_get_functiondef('private.plot_rarity_for(integer,integer)'::regprocedure);
  n := replace(d, $a$  v_city := private.city_at(p_gx, p_gy);
$a$, $a$  v_city := private.city_at(p_gx, p_gy);
  if v_city is not null then
    if abs(private.cell_roll('crown_country', p_gx, p_gy)) % 1000000
         < coalesce((private.cfg('rarity_abilities') -> 'crown_country' ->> 'ppm')::numeric, 5) * v_um
       and not private.crown_country_held(v_city ->> 'country') then
      return 'crown_country';
    end if;
    if abs(private.cell_roll('crown_state', p_gx, p_gy)) % 1000000
         < coalesce((private.cfg('rarity_abilities') -> 'crown_state' ->> 'ppm')::numeric, 50) * v_um
       and not private.crown_state_held(v_city ->> 'country', v_city ->> 'state') then
      return 'crown_state';
    end if;
  end if;
$a$);
  if n = d then raise exception 'crown tiers: plot_rarity_for anchor not found'; end if;
  execute n;

  -- two players can't take the same kingdom's Crown at once: lock it and check again (the City Crown already does)
  d := pg_get_functiondef('private.take_plot(uuid,integer,integer,text,jsonb)'::regprocedure);
  n := replace(d, $a$  v_rarity := private.plot_rarity_for(p_gx, p_gy);
$a$, $a$  v_rarity := private.plot_rarity_for(p_gx, p_gy);
  if v_rarity = 'crown_country' then
    perform pg_advisory_xact_lock(hashtext('crown_country:' || coalesce(private.city_at(p_gx, p_gy) ->> 'country', '')));
    if private.crown_country_held(private.city_at(p_gx, p_gy) ->> 'country') then v_rarity := 'mythic'; end if;
  elsif v_rarity = 'crown_state' then
    perform pg_advisory_xact_lock(hashtext('crown_state:' || coalesce(private.city_at(p_gx, p_gy) ->> 'country', '') || '/' || coalesce(private.city_at(p_gx, p_gy) ->> 'state', '')));
    if private.crown_state_held(private.city_at(p_gx, p_gy) ->> 'country', private.city_at(p_gx, p_gy) ->> 'state') then v_rarity := 'mythic'; end if;
  end if;
$a$);
  if n = d then raise exception 'crown tiers: take_plot anchor not found'; end if;
  execute n;
end $$;

