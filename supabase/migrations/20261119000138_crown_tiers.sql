/** how many OTHER players own land in a Crown's kingdom */
create or replace function private.kingdom_rivals(p_tier text, p_city int, p_holder uuid) returns int language sql stable as $$
  select count(distinct p.owner_id)::int
  from public.world_cities k
  join public.world_cities c on case p_tier when 'crown' then c.id = k.id
                                            when 'crown_state' then c.country = k.country and c.state = k.state
                                            else c.country = k.country end
  join public.world_plots p on p.city_id = c.id
  where k.id = p_city and p.owner_id is not null and p.owner_id <> p_holder
$$;
/** 0 … 1: how strong a Crown is right now */
create or replace function private.crown_strength(p_tier text, p_city int, p_holder uuid) returns numeric language sql stable as $$
  select least(1, private.kingdom_rivals(p_tier, p_city, p_holder)::numeric
                  / greatest(coalesce((private.cfg('rarity_abilities') -> p_tier ->> 'need')::numeric,
                                      case p_tier when 'crown' then 5 when 'crown_state' then 25 else 100 end), 1))
$$;
/** the Crowns' share of the all-your-rent multiplier, in percent: your best Crown of each tier, scaled by its strength */
create or replace function private.crown_pct(p_uid uuid) returns numeric language sql stable as $$
  select coalesce(sum(x.best), 0) from (
    select max(private.crown_strength(p.rarity, p.city_id, p_uid))
           * coalesce((private.cfg('rarity_abilities') -> p.rarity ->> 'pct')::numeric, case p.rarity when 'crown' then 50 when 'crown_state' then 400 else 900 end) as best
    from public.world_plots p
    where p.owner_id = p_uid and p.rarity in ('crown', 'crown_state', 'crown_country') and p.city_id is not null
    group by p.rarity) x
$$;
do $$
declare d text; n text;
begin
  d := pg_get_functiondef('private.rent_mult(uuid)'::regprocedure);
  n := replace(d, $a$+ coalesce((a -> 'crown' ->> 'pct')::numeric, 100) * least((select count(*) from public.world_plots where owner_id = p_uid and rarity = 'crown'), coalesce((a -> 'crown' ->> 'max')::int, 1))$a$,
                  $a$+ private.crown_pct(p_uid)$a$);
  if n = d then raise exception 'crown tiers: rent_mult anchor not found'; end if;
  execute n;
end $$;

-- ---- the Crowns of the world -------------------------------------------------------------------------------------------
drop function if exists public.crowns();
create function public.crowns() returns jsonb language sql stable security definer set search_path = public, pg_temp as $$
  select jsonb_build_object(
    'total', (select count(*) from public.world_cities),
    'states', (select count(distinct (country, state)) from public.world_cities),
    'countries', (select count(distinct country) from public.world_cities),
    'held', coalesce((select jsonb_agg(jsonb_build_object(
        'tier', p.rarity,
        'city', case p.rarity when 'crown' then c.name when 'crown_state' then c.state else c.country_name end,
        'country', c.country, 'holder', pr.username, 'since', p.claimed_at, 'mine', p.owner_id = auth.uid(),
        'strength', private.crown_strength(p.rarity, p.city_id, p.owner_id),
        'rivals', private.kingdom_rivals(p.rarity, p.city_id, p.owner_id),
        'need', coalesce((private.cfg('rarity_abilities') -> p.rarity ->> 'need')::int, 5))
      order by case p.rarity when 'crown_country' then 0 when 'crown_state' then 1 else 2 end, p.claimed_at desc)
      from public.world_plots p join public.world_cities c on c.id = p.city_id join public.profiles pr on pr.id = p.owner_id
      where p.rarity in ('crown', 'crown_state', 'crown_country') and p.owner_id is not null), '[]'::jsonb))
$$;
revoke all on function public.crowns() from public, anon;
grant execute on function public.crowns() to authenticated;

