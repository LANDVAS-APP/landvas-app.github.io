-- ---- which city (and so state and country) a plot is in ------------------------------------------------------------
create or replace function private.city_at(p_gx int, p_gy int) returns jsonb language sql stable as $$
  select jsonb_build_object('id', c.id::text, 'name', c.name, 'country', c.country, 'country_name', c.country_name, 'state', c.state,
                            'gx', c.gx, 'gy', c.gy, 'radius', c.radius)
  from public.world_cities c
  where c.gx between p_gx - 2500 and p_gx + 2500 and c.gy between p_gy - 2500 and p_gy + 2500
    and ((p_gx - c.gx)::numeric ^ 2 + (p_gy - c.gy)::numeric ^ 2) <= (c.radius::numeric ^ 2)
  order by ((p_gx - c.gx)::numeric ^ 2 + (p_gy - c.gy)::numeric ^ 2) / (c.radius::numeric ^ 2), c.id
  limit 1
$$;

